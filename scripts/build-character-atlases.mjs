/**
 * Deterministic v3 character atlas builder.
 *
 * Usage:
 *   node scripts/build-character-atlases.mjs
 *   node scripts/build-character-atlases.mjs --ids mostasa,enemy_001
 *
 * The default is intentionally strict and requires all configured alpha
 * sources. --ids enables safe incremental replacement while ImageGen assets
 * are produced; untouched manifest entries and atlases remain unchanged.
 */

import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'fs';
import { dirname, join } from 'path';
import { fileURLToPath } from 'url';
import { format } from 'prettier';
import { decodePng, encodePng } from './png-lib.mjs';
import {
  CHARACTER_IDS,
  CHARACTER_LAYOUTS,
  outputFileFor,
  sourceFileFor,
} from './character-atlas-config.mjs';
import { buildCharacterAtlas, validateCharacterAtlas } from './character-atlas-lib.mjs';

const SCRIPT_DIR = dirname(fileURLToPath(import.meta.url));
const ROOT = join(SCRIPT_DIR, '..');
const SOURCE_DIR = join(ROOT, 'assets', 'generated', 'characters-v2');
const OUTPUT_DIR = join(ROOT, 'public', 'assets', 'characters');
const JSON_MANIFEST = join(OUTPUT_DIR, 'character-atlas-manifest.json');
const TS_MANIFEST = join(ROOT, 'src', 'game', 'data', 'CharacterAssetManifest.ts');

function parseIds(argv) {
  const index = argv.indexOf('--ids');
  if (index < 0) return [...CHARACTER_IDS];
  const value = argv[index + 1];
  if (!value) throw new Error('--ids requires a comma-separated value');
  const ids = [
    ...new Set(
      value
        .split(',')
        .map((id) => id.trim())
        .filter(Boolean),
    ),
  ];
  if (ids.length === 0) throw new Error('--ids did not contain any ids');
  for (const id of ids) {
    if (!CHARACTER_LAYOUTS[id]) throw new Error(`unknown character id: ${id}`);
  }
  return ids;
}

function readExistingManifest() {
  if (!existsSync(JSON_MANIFEST)) return {};
  return JSON.parse(readFileSync(JSON_MANIFEST, 'utf8'));
}

function orderedManifest(entries) {
  const ordered = {};
  for (const id of CHARACTER_IDS) {
    if (entries[id]) ordered[id] = entries[id];
  }
  return ordered;
}

function renderTypescriptManifest(manifest) {
  return `/**\n * Generated by scripts/build-character-atlases.mjs.\n * Do not hand-edit geometry; rebuild the corresponding atlas instead.\n */\n\nexport interface CharacterSegmentationMetadata {\n  readonly strategy: 'alpha-components-voronoi-v3';\n  readonly sourceWidth: number;\n  readonly sourceHeight: number;\n  readonly rootCount: number;\n  readonly fragmentCount: number;\n  readonly rowRootCounts: readonly number[];\n  readonly rowBounds: readonly (readonly [number, number])[];\n  readonly rowBoundaryAlphaPixels: readonly number[];\n  readonly sourceVisiblePixels: number;\n  readonly uniformScale: number;\n}\n\nexport interface CharacterAssetMetadata {\n  readonly file: string;\n  readonly frameWidth: number;\n  readonly frameHeight: number;\n  readonly cols: number;\n  readonly rows: number;\n  /** Populated, unique animation frames. */\n  readonly frameCount: number;\n  /** Physical cells in the rectangular atlas. */\n  readonly totalCells?: number;\n  readonly actualFrameCount?: number;\n  readonly emptyCells?: readonly number[];\n  readonly referenceBodyHeight: number;\n  readonly footAnchorY: number;\n  readonly gutter: number;\n  readonly pipelineVersion: number;\n  readonly segmentation?: CharacterSegmentationMetadata;\n}\n\nexport const CHARACTER_ASSET_MANIFEST = ${JSON.stringify(manifest, null, 2)} as const satisfies Record<string, CharacterAssetMetadata>;\n\nexport type CharacterAssetKey = keyof typeof CHARACTER_ASSET_MANIFEST;\n`;
}

async function main() {
  const requestedIds = parseIds(process.argv.slice(2));
  const missing = requestedIds.filter((id) => !existsSync(join(SOURCE_DIR, sourceFileFor(id))));
  if (missing.length > 0) {
    throw new Error(`missing alpha sources: ${missing.map(sourceFileFor).join(', ')}`);
  }

  const existing = readExistingManifest();
  const isPartial = requestedIds.length !== CHARACTER_IDS.length;
  if (isPartial) {
    const absentEntries = CHARACTER_IDS.filter((id) => !existing[id] && !requestedIds.includes(id));
    if (absentEntries.length > 0) {
      throw new Error(
        `partial build needs existing manifest entries for: ${absentEntries.join(', ')}`,
      );
    }
  }

  // Build and validate everything in memory before replacing any public file.
  const pending = [];
  for (const id of requestedIds) {
    const sourcePath = join(SOURCE_DIR, sourceFileFor(id));
    const source = decodePng(readFileSync(sourcePath));
    const result = buildCharacterAtlas(id, CHARACTER_LAYOUTS[id], source);
    const validation = validateCharacterAtlas(
      id,
      result.image,
      result.metadata,
      CHARACTER_LAYOUTS[id],
    );
    if (validation.errors.length > 0) {
      throw new Error(`${id} failed preflight:\n  - ${validation.errors.join('\n  - ')}`);
    }
    pending.push({ id, ...result, validation });
  }

  mkdirSync(OUTPUT_DIR, { recursive: true });
  const merged = { ...existing };
  for (const result of pending) {
    writeFileSync(
      join(OUTPUT_DIR, outputFileFor(result.id)),
      encodePng(result.image.width, result.image.height, result.image.rgba),
    );
    merged[result.id] = result.metadata;
  }

  const manifest = orderedManifest(merged);
  const absentEntries = CHARACTER_IDS.filter((id) => !manifest[id]);
  if (absentEntries.length > 0) {
    throw new Error(`manifest remains incomplete: ${absentEntries.join(', ')}`);
  }
  writeFileSync(JSON_MANIFEST, `${JSON.stringify(manifest, null, 2)}\n`);
  const typescriptManifest = await format(renderTypescriptManifest(manifest), {
    parser: 'typescript',
    singleQuote: true,
  });
  writeFileSync(TS_MANIFEST, typescriptManifest);

  for (const result of pending) {
    const metrics = result.validation.metrics;
    const segmentation = result.metadata.segmentation;
    console.log(
      `${result.id.padEnd(10)} ${result.image.width}x${result.image.height}` +
        ` (${result.metadata.cols}x${result.metadata.rows} @ ${result.metadata.frameWidth}x${result.metadata.frameHeight})` +
        ` frames=${result.metadata.actualFrameCount}/${result.metadata.totalCells}` +
        ` ref=${result.metadata.referenceBodyHeight}px foot=${result.metadata.footAnchorY}px` +
        ` soft=${metrics.semiTransparent}` +
        ` roots=${segmentation.rootCount} fragments=${segmentation.fragmentCount}` +
        ` scale=${segmentation.uniformScale}` +
        ` rowCuts=[${segmentation.rowBoundaryAlphaPixels.join(',')}]`,
    );
  }
  console.log(`manifest -> ${JSON_MANIFEST}`);
  console.log(`typescript -> ${TS_MANIFEST}`);
}

try {
  await main();
} catch (error) {
  console.error(error instanceof Error ? error.message : error);
  process.exitCode = 1;
}
